#!/usr/bin/env bash
# One-time server setup for the Onvioo panel (Ubuntu 22.04+/Debian 12). Run as root:
#   sudo bash server-setup.sh [public-ip-or-hostname]
# It installs Docker, creates a "deploy" user for GitHub Actions, writes /opt/onvioo/.env
# with fresh random secrets, schedules the cron jobs and backups, and finally prints the
# values to put in GitHub → Settings → Secrets. No password ever leaves the server.
set -euo pipefail

[[ $EUID -eq 0 ]] || { echo "Run as root: sudo bash $0"; exit 1; }

APP_DIR=/opt/onvioo
DEPLOY_USER=deploy
HOST=${1:-$(hostname -I | awk '{print $1}')}
SSH_PORT=$(sshd -T 2>/dev/null | awk '/^port /{print $2; exit}')
SSH_PORT=${SSH_PORT:-22}

echo "==> Timezone: Asia/Tehran (the cron schedules below use it)"
timedatectl set-timezone Asia/Tehran || true

echo "==> Installing Docker"
export DEBIAN_FRONTEND=noninteractive
apt-get update -q
apt-get install -yq ca-certificates curl cron openssl docker.io
if ! docker compose version >/dev/null 2>&1; then
  apt-get install -yq docker-compose-v2 || apt-get install -yq docker-compose-plugin || true
fi
docker compose version >/dev/null 2>&1 || { echo "!! docker compose plugin is missing; install it and run this script again"; exit 1; }

# Docker Hub refuses pulls from Iranian IPs; a local mirror serves postgres and caddy images.
if [[ ! -f /etc/docker/daemon.json ]]; then
  mkdir -p /etc/docker
  cat > /etc/docker/daemon.json <<'JSON'
{
  "registry-mirrors": ["https://docker.arvancloud.ir"],
  "log-driver": "json-file",
  "log-opts": { "max-size": "20m", "max-file": "3" }
}
JSON
fi
systemctl enable --now docker
systemctl restart docker

echo "==> Deploy user and $APP_DIR"
id "$DEPLOY_USER" >/dev/null 2>&1 || useradd -m -s /bin/bash "$DEPLOY_USER"
usermod -aG docker "$DEPLOY_USER"
mkdir -p "$APP_DIR"
chown "$DEPLOY_USER:$DEPLOY_USER" "$APP_DIR"

echo "==> Secrets in $APP_DIR/.env"
if [[ ! -f "$APP_DIR/.env" ]]; then
  rand() { openssl rand -hex 32; }
  cat > "$APP_DIR/.env" <<ENV
# Generated by server-setup.sh. Edit with: sudo -u deploy nano $APP_DIR/.env
# then apply with: cd $APP_DIR && sudo -u deploy docker compose up -d

# Domain for HTTPS (e.g. panel.onvioo.ir). Leave empty to serve on http://$HOST
DOMAIN=
APP_URL=http://$HOST

POSTGRES_PASSWORD=$(rand)
CRON_SECRET=$(rand)
TOKEN_SECRET=$(rand)
BOT_WEBHOOK_SECRET=$(rand)

# SMS login codes (Kavenegar). Until set, codes appear in: docker compose logs app
KAVENEGAR_API_KEY=
KAVENEGAR_OTP_TEMPLATE=
KAVENEGAR_NOTIFY_TEMPLATE=

# File storage (ArvanCloud S3)
S3_ENDPOINT=https://s3.ir-thr-at1.arvanstorage.ir
S3_REGION=default
S3_BUCKET=
S3_ACCESS_KEY=
S3_SECRET_KEY=

# Bots, payments, AI, subtitles (all optional; see env.example for every option)
BALE_BOT_TOKEN=
BALE_CHAT_ID=
ZARINPAL_MERCHANT_ID=
ANTHROPIC_API_KEY=
WHISPER_URL=
ENV
  chown "$DEPLOY_USER:$DEPLOY_USER" "$APP_DIR/.env"
  chmod 600 "$APP_DIR/.env"
else
  echo "    $APP_DIR/.env already exists, left as is"
fi

echo "==> Scheduled jobs and daily backup"
cat > /etc/cron.d/onvioo <<CRON
SHELL=/bin/bash
*/5 * * * * $DEPLOY_USER $APP_DIR/cron.sh monitor   >/dev/null 2>&1
*   * * * * $DEPLOY_USER flock -n /tmp/onvioo-video.lock $APP_DIR/cron.sh video >/dev/null 2>&1
0   6 * * * $DEPLOY_USER $APP_DIR/cron.sh instagram >/dev/null 2>&1
0   7 * * * $DEPLOY_USER $APP_DIR/cron.sh monthly   >/dev/null 2>&1
0   8 * * 6 $DEPLOY_USER $APP_DIR/cron.sh weekly    >/dev/null 2>&1
0   9 * * * $DEPLOY_USER $APP_DIR/cron.sh daily     >/dev/null 2>&1
30  3 * * * $DEPLOY_USER $APP_DIR/backup.sh         >/dev/null 2>&1
CRON

if command -v ufw >/dev/null && ufw status | grep -q "Status: active"; then
  ufw allow 80/tcp && ufw allow 443/tcp
fi

echo "==> SSH key for GitHub Actions (allowed to log in only as $DEPLOY_USER)"
DEPLOY_HOME=$(getent passwd "$DEPLOY_USER" | cut -d: -f6)
install -d -m 700 -o "$DEPLOY_USER" -g "$DEPLOY_USER" "$DEPLOY_HOME/.ssh"
KEY_DIR=$(mktemp -d)
ssh-keygen -q -t ed25519 -N "" -C "github-actions-deploy" -f "$KEY_DIR/key"
cat "$KEY_DIR/key.pub" >> "$DEPLOY_HOME/.ssh/authorized_keys"
chown "$DEPLOY_USER:$DEPLOY_USER" "$DEPLOY_HOME/.ssh/authorized_keys"
chmod 600 "$DEPLOY_HOME/.ssh/authorized_keys"

if [[ "$SSH_PORT" == 22 ]]; then KNOWN_HOST=$HOST; else KNOWN_HOST="[$HOST]:$SSH_PORT"; fi
KNOWN_HOSTS=$(for f in /etc/ssh/ssh_host_*_key.pub; do echo "$KNOWN_HOST $(cut -d' ' -f1,2 "$f")"; done)

cat <<OUT

================================================================
 Done. In GitHub open the repo → Settings → Secrets and variables
 → Actions → New repository secret, and add these four secrets:
================================================================

SERVER_HOST
$HOST

SERVER_PORT
$SSH_PORT

SERVER_SSH_KEY   (copy everything including the BEGIN/END lines)
$(cat "$KEY_DIR/key")

SERVER_KNOWN_HOSTS
$KNOWN_HOSTS

================================================================
 Then run the "Deploy" workflow from the Actions tab.
 Do not send these values to anyone; they belong only in GitHub.
================================================================
OUT
rm -rf "$KEY_DIR"
